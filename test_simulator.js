const puppeteer = require('C:/Users/Windows User/.gemini/antigravity-ide/brain/144e5134-e54d-4a3f-9139-fb9cd09fd05a/scratch/node_modules/puppeteer-core');
const path = require('path');
const fs = require('fs');

(async () => {
  const edgePath = 'C:\\Program Files (x86)\\Microsoft\\Edge\\Application\\msedge.exe';
  const chromePath = 'C:\\Program Files\\Google\\Chrome\\Application\\chrome.exe';
  const execPath = fs.existsSync(edgePath) ? edgePath : chromePath;

  console.log('Testing 2-Player Simulator via:', execPath);
  const browser = await puppeteer.launch({
    executablePath: execPath,
    headless: true,
    args: ['--no-sandbox', '--disable-setuid-sandbox', '--allow-file-access-from-files']
  });

  const page = await browser.newPage();
  await page.setViewport({ width: 1400, height: 800 });

  const simUrl = 'file:///' + path.join(__dirname, 'simulator.html').replace(/\\/g, '/');
  await page.goto(simUrl, { waitUntil: 'networkidle0' });
  await new Promise(r => setTimeout(r, 1000));

  // Get frames
  const frames = page.frames();
  console.log('Total frames:', frames.length);

  const p1Frame = frames.find(f => f.name() === '' && f !== page.mainFrame());
  // Find frame 1 and 2
  const iframes = await page.$$('iframe');
  const frame1 = await iframes[0].contentFrame();
  const frame2 = await iframes[1].contentFrame();

  console.log('Clicking CREATE on Player 1...');
  await frame1.click('#btnCreate');
  await new Promise(r => setTimeout(r, 1500));

  const code = await frame1.$eval('#partyCodeDisplay', el => el.textContent.trim());
  console.log('Party Code generated by Player 1:', code);

  console.log('Joining with code on Player 2...');
  await frame2.type('#inputCode', code);
  await frame2.click('#btnJoin');
  await new Promise(r => setTimeout(r, 1800));

  // Open chat on Player 1
  await frame1.click('#btnPartyChat');
  await new Promise(r => setTimeout(r, 400));
  await frame1.type('#chatInput', 'HELLO FROM PLAYER 1!');
  await frame1.click('#btnSendChat');
  await new Promise(r => setTimeout(r, 600));

  // Check Player 2 chat badge or messages
  const p2Badge = await frame2.$eval('#chatBadge', el => el.textContent.trim());
  console.log('Player 2 unread chat badge count:', p2Badge);

  // Open chat on Player 2 to see the message
  await frame2.click('#btnPartyChat');
  await new Promise(r => setTimeout(r, 400));

  // Take screenshot of the entire 2-player simulator
  await page.screenshot({ path: path.join(__dirname, 'screenshot_simulator.png') });
  console.log('Saved screenshot_simulator.png');

  await browser.close();
  console.log('Simulator test passed with flying colors!');
})();
